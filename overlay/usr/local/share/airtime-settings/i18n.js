// --- tiny runtime -----------------------------------------------------------
let LANG = "en";       // resolved OS language, from /cgi-bin/lang
let DETECTED = "";     // geo-IP detection, if any
let CHOSEN = "auto";   // explicit choice, or "auto"

function t(key, vars) {
  let s = (I18N[LANG] && I18N[LANG][key]) || I18N.en[key] || key;
  if (vars) for (const v in vars) s = s.split("{" + v + "}").join(vars[v]);
  return s;
}

// Elements opt in with data-i18n (text) / data-i18n-ph (placeholder), so the
// same pass can re-run on a language change without touching dynamic content.
function applyI18n() {
  document.documentElement.lang = LANG;
  document.documentElement.dir = LANG === "ar" ? "rtl" : "ltr";
  document.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll("[data-i18n-ph]").forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
}

async function initI18n() {
  try {
    const r = await (await fetch("/cgi-bin/lang")).json();
    LANG = I18N[r.effective] ? r.effective : "en";
    DETECTED = r.detected || "";
    CHOSEN = r.lang || "auto";
  } catch {}
  applyI18n();
}
